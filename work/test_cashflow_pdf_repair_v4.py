PERIODS={'current':{'period_end':'2030-09-28'},'comparison':{'period_end':'2029-09-30'}}
UNIT='(In millions, except number of shares which are reflected in thousands and par value)'


def statement(kind='cf',annual='Twelve Months Ended',unit=None):
 title='CONDENSED CONSOLIDATED STATEMENTS OF CASH FLOWS' if kind=='cf' else 'CONDENSED CONSOLIDATED BALANCE SHEETS'
 head=['Apple Inc.',title,'(Unaudited)',unit or ('(In millions)' if kind=='cf' else UNIT)]
 if kind=='cf':head.append(annual)
 head+=['September 28,                 September 30,','2030                           2029']
 rows=['Net income        $ 111       $ 222',
       'Adjustments to reconcile net income to cash generated by operating activities:',
       'Depreciation        3        4',
       'Cash generated by operating activities     333      444'] if kind=='cf' else ['Total assets     $ 555     $ 666']
 return '\n'.join(head+rows)


def locator():
 return dict(row_label='Net income',header_dates=['2030-09-28','2029-09-30'],
  header_literals=['September 28, September 30,','2030 2029'],financial_column_index_0based=0)


class FakePage:
 def __init__(self):self.chars=[]
 def add(self,text,x,y):
  for ch in text:
   self.chars.append((ch,(x,y,x+4,y+8)))
   x+=5
  return self
 def count_chars(self):return len(self.chars)
 def get_text_range(self,index,count):return ''.join(x[0] for x in self.chars[index:index+count])
 def get_charbox(self,index):return self.chars[index][1]


def page(values=('111','222'),label='Net income',y=400):
 p=FakePage().add('September 28,',340,500).add('September 30,',440,500)
 p.add('2030',375,480).add('2029',475,480)
 p.add(label,20,y).add(values[0],380,y).add(values[1],480,y)
 return p


def geometry(p,values=('111','222'),loc=None):
 return m.geometry_rows(m.physical_rows(p),loc or locator(),list(values))


