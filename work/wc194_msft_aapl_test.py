"""Synthetic signed operating-row, annual-column and geometry tests."""
from copy import deepcopy
import unittest
import wc194_msft_aapl as m

PERIODS={'current':dict(period_start='2029-07-01',period_end='2030-06-30',days_inclusive=365),
         'comparison':dict(period_start='2028-07-01',period_end='2029-06-30',days_inclusive=365)}
LABELS=['Accounts receivable, net','Inventories','Accounts payable']


def html(labels=None,values=None,duplicate=False,section='Changes in operating assets and liabilities:',annual='Twelve Months Ended June 30,'):
    labels=labels or LABELS;values=values or ['(120)','30','—']
    body=''.join('<tr><td>'+k+'</td><td>'+v+'</td><td>(9)</td></tr>' for k,v in zip(labels,values))
    if duplicate:body+='<tr><td>Inventories</td><td>7</td><td>8</td></tr>'
    return ('<h2>CASH FLOWS STATEMENTS</h2><p>(In millions)</p><table><tr><td></td><td colspan="2">'+annual+'</td></tr>'
        '<tr><td></td><td>2030</td><td>2029</td></tr><tr><td>Net income</td><td>$ 100</td><td>$ 90</td></tr>'
        '<tr><td>Adjustments to reconcile net income to cash generated by operating activities:</td><td></td><td></td></tr>'
        '<tr><td>Depreciation</td><td>9</td><td>8</td></tr><tr><td>'+section+'</td><td></td><td></td></tr>'+body+
        '<tr><td>Vendor non-trade receivables</td><td>(400)</td><td>500</td></tr>'
        '<tr><td>Net cash from operations</td><td>100</td><td>90</td></tr>'
        '<tr><td>Investing</td><td></td><td></td></tr><tr><td>Accounts payable</td><td>999</td><td>888</td></tr></table>').encode()


def event(raw=None):
    raw=raw if raw is not None else html();loc=m.base.html2.inventory(raw,PERIODS)['candidates']['current']['operating_cash_flow'][0]
    return dict(event_id='MSFT:FY2030:2030-07-25',symbol='MSFT',fiscal_year=2030,release_date='2030-07-25',available_from='2030-07-26',
        periods=deepcopy(PERIODS),fields={'current':{'operating_cash_flow':{'locator':loc}}},source={'path':'synthetic.html','sha256':m.sha(raw)},
        cash_quality_admission={'admitted':True,'reasons':[]},inherited_rejection_codes=[],accounting_review_flags=[],identity={})


def pdf_text(labels=None,values=None):
    rows=[k+'    '+v+'    (9)' for k,v in zip(labels or LABELS,values or ['(120)','30','70'])]
    return '\n'.join(['Apple Inc.','CONDENSED CONSOLIDATED STATEMENTS OF CASH FLOWS','(Unaudited)','(In millions)',
        'Twelve Months Ended','June 30,                   June 30,','2030                      2029',
        'Net income    $ 100      $ 90','Adjustments to reconcile net income to cash generated by operating activities:',
        'Depreciation    4    5','Changes in operating assets and liabilities:']+rows+[
        'Vendor non-trade receivables    (99)    44','Cash generated by operating activities    110    100','Investing activities:'])


def pdf_event(text):
    e=event();e['symbol']='AAPL'
    e['fields']['current']['operating_cash_flow']['locator']=m.base.pdf4.inventory([text],PERIODS)['candidates']['current']['operating_cash_flow'][0]
    return e


class TextPage:
    def __init__(self):self.chars=[]
    def add(self,text,x,y):
        for c in text:self.chars.append((c,(x,y,x+4,y+8)));x+=5
        return self
    def count_chars(self):return len(self.chars)
    def get_text_range(self,index,count):return ''.join(c[0] for c in self.chars[index:index+count])
    def get_charbox(self,index):return self.chars[index][1]


class Tests(unittest.TestCase):
    def test_signed_positive_negative_zero_dash(self):
        for literal,want in [('(1,234)','-1234'),('-12','-12'),('9','9'),('0','0'),('—','0'),('-','0')]:
            result=m.signed_cell(literal,'1000000');self.assertEqual(result['signed_value_decimal'],want);self.assertEqual(result['signed_literal'],literal)
        with self.assertRaises(ValueError):m.signed_cell('—','1000000',False)
    def test_no_digit_join_or_missing_zero(self):
        for literal in ('','(1 234)','12%','NaN','(12','12 34'):
            with self.assertRaises(ValueError):m.signed_cell(literal,'1000000')
    def test_html_three_distinct_operating_rows(self):
        raw=html();e=event(raw);saved=deepcopy(e);fields,notes=m.html_fields(raw,e)
        self.assertEqual([fields[k]['signed_value_decimal'] for k in m.COMPONENTS],['-120','30','0'])
        self.assertTrue(fields['accounts_payable']['explicit_dash_zero']);self.assertEqual(e,saved)
        for f in fields.values():
            self.assertEqual(f['locator']['logical_columns'],[1]);self.assertEqual(f['locator']['period_end'],'2030-06-30')
            self.assertEqual(f['row_text_sha256'],m.sha(f['row_text'].encode()));self.assertIsNone(f['currency_literal'])
    def test_combined_or_vendor_rows_held(self):
        for labels,key in [(['Vendor non-trade receivables','Inventories','Accounts payable'],'accounts_receivable'),
            (['Accounts receivable and other assets','Inventories','Accounts payable'],'accounts_receivable'),
            (['Accounts receivable','Inventories','Accounts payable and other liabilities'],'accounts_payable')]:
            raw=html(labels=labels);fields,notes=m.html_fields(raw,event(raw));self.assertIsNone(fields[key]);self.assertTrue(notes[key]['hold_reasons'])
    def test_duplicate_keeps_unambiguous_other_components(self):
        raw=html(duplicate=True);f,n=m.html_fields(raw,event(raw));self.assertIsNone(f['inventories']);self.assertIsNotNone(f['accounts_payable'])
    def test_no_operating_changes_no_balance_sheet_fallback(self):
        raw=html(section='Balance sheet balances:')
        with self.assertRaisesRegex(ValueError,'working-capital'):m.html_fields(raw,event(raw))
    def test_cfo_binding_wrong_year(self):
        raw=html();e=event(raw);e['fields']['current']['operating_cash_flow']['locator']['period_end']='2029-06-30'
        with self.assertRaises(ValueError):m.html_fields(raw,e)
    def test_html_cross_period_spanning_amount_held(self):
        raw=html().replace(b'<td>(120)</td><td>(9)</td>',b'<td colspan="2">(120)</td>')
        f,n=m.html_fields(raw,event(raw));self.assertIsNone(f['accounts_receivable'])
    def test_current_pdf_column_and_signed_values(self):
        text=pdf_text();f,n=m.pdf_layout([text],pdf_event(text))
        self.assertEqual([f[k]['signed_value_decimal'] for k in m.COMPONENTS],['-120','30','70'])
        self.assertEqual(f['accounts_receivable']['all_row_cells'],['(120)','(9)'])
        self.assertEqual(f['accounts_receivable']['locator']['financial_column_index_0based'],0)
    def test_pdf_split_label_glyphs_preserve_full_row_identity(self):
        text=pdf_text().replace('Accounts receivable, net','Accountsreceivable,net').replace('Accounts payable','Accountspayable')
        f,n=m.pdf_layout([text],pdf_event(text));self.assertEqual(f['accounts_receivable']['signed_value_decimal'],'-120')
        self.assertEqual(f['accounts_payable']['signed_value_decimal'],'70')
    def test_pdf_merged_scope_and_empty_cell(self):
        for labels in (['Accounts receivable','Inventories','Accounts payable and accrued expenses'],['Vendor non-trade receivables','Inventories','Accounts payable']):
            text=pdf_text(labels=labels);f,n=m.pdf_layout([text],pdf_event(text));self.assertTrue(any(v is None for v in f.values()))
        for tail in ('1 23 (9)','(10) junk (9)','(10) (9) 3'):
            with self.assertRaises(ValueError):m.monetary_columns(tail,2)
    def test_pdf_dash_and_parenthesis_space(self):
        raw,clean=m.monetary_columns('(120 ) —',2);self.assertEqual(raw,['(120 )','—']);self.assertEqual(clean,['(120)','—'])
    def test_geometry_current_cell_and_wrong_column(self):
        page=TextPage().add('June 30,',440,500).add('June 30,',620,500).add('2030',470,480).add('2029',650,480)
        page.add('Accounts receivable, net',20,400).add('(120)',480,400).add('(9)',660,400)
        loc=dict(row_label='Accounts receivable, net',header_dates=['2030-06-30','2029-06-30'],header_literals=['June 30, June 30,','2030 2029'],financial_column_index_0based=0)
        geometry=m.base.pdf4.geometry_rows(m.base.pdf4.physical_rows(page),loc,['(120)','(9)'])
        self.assertEqual(geometry['selected_cell']['text'],'(120)')
        with self.assertRaises(ValueError):m.base.pdf4.geometry_rows(m.base.pdf4.physical_rows(page),loc,['(121)','(9)'])
    def test_geometry_reconciliation_requires_exact_glyphs_and_year_columns(self):
        page=TextPage().add('June 30,',440,500).add('June 30,',620,500).add('2030',470,480).add('2029',650,480)
        page.add('Accounts payable',20,400).add('9,448',480,400).add('(9)',660,400)
        loc=dict(row_label='Accounts payable',header_dates=['2030-06-30','2029-06-30'],header_literals=['June 30, June 30,','2030 2029'],financial_column_index_0based=0,scale='1000000')
        cells,g=m.geometry_reconcile(m.base.pdf4.physical_rows(page),loc,'9,4 4 8      (9)')
        self.assertEqual(cells,['9,448','(9)']);self.assertEqual(g['selected_cell']['text'],'9,448')
        for bad in ('9,4 4 9 (9)','9,448','94 48 (9)','9,448 (9) 0'):
            with self.assertRaises(ValueError):m.geometry_reconcile(m.base.pdf4.physical_rows(page),loc,bad)
    def test_inherited_hold_not_upgraded(self):
        e=event();f,n=m.html_fields(html(),e);e['cash_quality_admission']=dict(admitted=False,reasons=['old_hold'])
        r=m.record(e,f,n);self.assertTrue(r['extraction_verified']);self.assertEqual(r['status'],'held');self.assertIn('inherited:old_hold',r['hold_reasons'])
    def test_wrong_scope_rejected_before_source_read(self):
        with self.assertRaisesRegex(ValueError,'Exact194'):m.gate('0'*64)

if __name__=='__main__':unittest.main()
