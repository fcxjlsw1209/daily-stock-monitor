"""Record independently read source-page amounts; no factor calculation."""
from datetime import datetime, timezone
from pathlib import Path
import stock_comp_source_v1_runner as source

PLAN_SHA = "ef563d83e864c3e592c75f232dccc1327aed9b1fc95b5a2115c703ad51df45ba"
# Transcribed by root from the rendered complete original cash-flow pages.
# Current-year left column only; all pages explicitly state "In millions".
READINGS = {
    2016: ("2016-09-24", "4,210", "4210"),
    2017: ("2017-09-30", "4,840", "4840"),
    2018: ("2018-09-29", "5,340", "5340"),
    2019: ("2019-09-28", "6,068", "6068"),
    2020: ("2020-09-26", "6,829", "6829"),
    2021: ("2021-09-25", "7,906", "7906"),
    2022: ("2022-09-24", "9,038", "9038"),
    2023: ("2023-09-30", "10,833", "10833"),
    2024: ("2024-09-28", "11,688", "11688"),
    2025: ("2025-09-27", "12,863", "12863"),
}


def main():
    root = Path(__file__).resolve().parents[1]
    plan = source.load_plan(root, PLAN_SHA)
    manifest = source.base.read(root, source.OUT + "/MANIFEST.json")
    source.safe.verify_hashes(root, {
        source.OUT + "/" + k: v for k, v in manifest["output_hashes"].items()
    })
    data = source.base.read(root, source.OUT + "/RAW_FACTS.json")
    pages = source.base.read(root, source.OUT + "/VISUAL_PAGES.json")
    source.require(pages["plan_sha256"] == PLAN_SHA, "Wrong rendered source plan")
    by_id = source.indexed(data["events"])
    records = []
    for page in pages["pages"]:
        event = by_id[page["event_id"]]
        year = event["fiscal_year"]
        end, display, decimal = READINGS[year]
        source.require(event["symbol"] == "AAPL", "Unexpected PDF issuer")
        source.require(event["periods"]["current"]["period_end"] == end,
                       "Visual current-year header disagreement")
        source.safe.verify_hashes(root, {
            page["source"]["path"]: page["source"]["sha256"],
            page["image"]["path"]: page["image"]["sha256"],
        })
        value = event["stock_compensation"]["value"]
        if value is not None:
            source.require(value["value_decimal"] == decimal and
                           str(value["scale"]) == "1000000", "Visual amount mismatch")
        records.append(dict(
            event_id=event["event_id"], source=page["source"],
            rendered_image=page["image"], page_1based=page["locator"]["page_1based"],
            statement="Condensed consolidated statements of cash flows (unaudited)",
            annual_header="Twelve Months Ended", current_period_end=end,
            column="left current-year column",
            row_label="Share-based compensation expense",
            scope="Standalone adjustment reconciling net income to cash generated by operating activities",
            displayed_amount=display, value_decimal=decimal, scale="1000000",
            currency_literal="$", currency_iso=None,
            v1_candidate_present=value is not None,
            v1_matches_visual=value is not None,
            v1_gap_requires_separate_version=value is None,
            inherited_hold=not event["cash_quality_admission"]["admitted"],
            accounting_note="Tax payments on equity awards appear separately in financing activities; not netted against this row.",
        ))
    source.require(len(records) == 10 and {r["current_period_end"] for r in records}
                   == {v[0] for v in READINGS.values()}, "Full ten-page visual review required")
    result = dict(
        schema_version=1, reviewed_utc=datetime.now(timezone.utc).isoformat(),
        stage="manual_pdf_source_review_not_admission",
        reviewer="root independently inspected ten full rendered source pages",
        plan_sha256=PLAN_SHA,
        raw_sha256=manifest["output_hashes"]["RAW_FACTS.json"],
        visual_pages_sha256=source.base.sha(root, source.OUT + "/VISUAL_PAGES.json"),
        recorder_sha256=source.base.sha(root, "work/record_stock_comp_pdf_visual_v1.py"),
        pages_reviewed=10, matching_existing_candidates=7,
        visible_values_missing_from_v1_candidates=3,
        passed_visual_identification=True, all_v1_pdf_values_extracted=False,
        events=records, new_fields_admitted=0, financial_ratios=0,
        strategy_trials=0, first_public_version_verified=False,
        complete_correction_history_verified=False,
        limitation="Visual identification does not remove existing source holds or establish the first-public data vintage.",
    )
    source.base.publish(root, source.OUT + "/PDF_VISUAL_REVIEW.json", result)
    print(source.safe.encoded(dict(pages_reviewed=10, matching=7, repair_required=3,
          output=source.OUT + "/PDF_VISUAL_REVIEW.json")).decode())


if __name__ == "__main__":
    main()
