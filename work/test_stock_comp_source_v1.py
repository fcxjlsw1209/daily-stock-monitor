import stock_comp_source_v1 as m

PERIODS = {
    'current': dict(period_start='2024-01-01', period_end='2024-12-31', days_inclusive=366),
    'comparison': dict(period_start='2023-01-01', period_end='2023-12-31', days_inclusive=365)}
LABEL = 'Stock-based compensation expense'
OUT = 'outputs/monthly_stock_comp_source_v1'


def row(label=LABEL, amount='314,159', prior='27,182'):
    return '<tr><td>'+label+'</td><td>'+amount+'</td><td>'+prior+'</td></tr>'


def table(label=LABEL, amount='314,159', title='CONSOLIDATED STATEMENTS OF CASH FLOWS',
          duration='Years Ended', extra='', ni='Net income', units='millions'):
    return ('<table><caption>'+title+' (in '+units+')</caption>'
            '<tr><td></td><td colspan="2">'+duration+'</td></tr>'
            '<tr><td></td><td>December 31, 2024</td><td>December 31, 2023</td></tr>'
            '<tr><td>'+ni+'</td><td>$ 111</td><td>$ 222</td></tr>'
            '<tr><td>Adjustments to reconcile net income to net cash from operations:</td></tr>'
            +row(label, amount)+extra+
            '<tr><td>Net cash from operations</td><td>333</td><td>444</td></tr></table>')


def parsed(text, periods=None):
    data = text.encode() if isinstance(text, str) else text
    p = PERIODS if periods is None else periods
    inv = m.inventory(data, p)
    return m.extract_current(data, p, inv), inv


def pdf_text(label=LABEL, amount='314,159', prior='27,182', extra='', duration='Twelve Months Ended'):
    return '\n'.join(['Apple Inc.', 'CONDENSED CONSOLIDATED STATEMENTS OF CASH FLOWS',
        '(Unaudited)', '(In millions)', duration,
        'December 31,                 December 31,', '2024                           2023',
        'Net income        $ 111       $ 222',
        'Adjustments to reconcile net income to cash generated by operating activities:',
        label+'        '+amount+'       '+prior, extra,
        'Cash generated by operating activities     333      444'])


def pdf_parsed(texts, geometry=None):
    with patch.object(m.base, 'pdf_texts', return_value=texts):
        inv = m.inventory(b'%PDF-synthetic', PERIODS, {})
        if geometry is None:
            return inv
        with patch.object(m.base, 'configure_pdf', return_value=(None, geometry)):
            return m.extract_current(b'%PDF-synthetic', PERIODS, inv, {}), inv


class FakePage:
    def __init__(self): self.chars = []
    def add(self, text, x, y):
        for ch in text:
            self.chars.append((ch, (x, y, x+4, y+8))); x += 5
        return self
    def count_chars(self): return len(self.chars)
    def get_text_range(self, index, count): return ''.join(x[0] for x in self.chars[index:index+count])
    def get_charbox(self, index): return self.chars[index][1]
    def close(self): pass
    def get_textpage(self): return self


class FakeDocument:
    def __init__(self, page): self.page = page
    def __getitem__(self, index):
        if index != 0: raise IndexError(index)
        return self.page
    def close(self): pass


def geometry(values=('314,159', '27,182'), label=LABEL, second_x=480):
    p = FakePage().add('December 31,', 340, 500).add('December 31,', 440, 500)
    p.add('2024', 375, 480).add('2023', 475, 480)
    p.add(label, 20, 400).add(values[0], 380, 400).add(values[1], second_x, 400)
    return p, SimpleNamespace(PdfDocument=lambda raw: FakeDocument(p))


class HTMLTests(unittest.TestCase):
    def test_metadata_only_and_current_exact_value(self):
        data = table().encode()
        with patch.object(m.html_repair, 'extract', side_effect=AssertionError('amount extraction')):
            inv = m.inventory(data, PERIODS)
        text = m.base.safe.encoded(inv).decode()
        self.assertNotIn('314,159', text); self.assertNotIn('27,182', text)
        self.assertEqual(len(inv['candidates']), 1)
        result = m.extract_current(data, PERIODS, inv)
        self.assertEqual(result['value']['value_decimal'], '314159')
        self.assertEqual(result['value']['scale'], '1000000')
        self.assertEqual(result['value']['period'], PERIODS['current'])
        self.assertNotIn('27,182', m.base.safe.encoded(result).decode())

    def test_signed_zero_and_comma_whitespace(self):
        for literal, expected in [('(314,159)', '-314159'), ('-314,159', '-314159'),
                                  ('0', '0'), ('314 , 159', '314159')]:
            with self.subTest(literal=literal):
                result, _ = parsed(table(amount=literal))
                self.assertEqual(result['value']['value_decimal'], expected)
                flags = {flag['code'] for flag in result['accounting_review_flags']}
                self.assertEqual('negative_stock_compensation_addback_requires_review' in flags,
                                 expected.startswith('-'))

    def test_share_and_stock_exact_labels(self):
        for label in ('Share-based compensation', 'Stock based compensation expense',
                      'Share\u2011based compensation expense', 'Stock-based compensation'):
            with self.subTest(label=label):
                result, _ = parsed(table(label=label))
                self.assertIsNotNone(result['value'])

    def test_separate_quarter_same_year_not_used(self):
        result, inv = parsed(table(amount='999', duration='Three Months Ended')+table())
        self.assertEqual(result['value']['value_decimal'], '314159')
        self.assertEqual(inv['candidates'][0]['table_index_zero_based'], 1)

    def test_same_table_quarter_annual_columns(self):
        text = ('<table><caption>CASH FLOWS STATEMENTS (in millions)</caption>'
                '<tr><td></td><td colspan="2">Three Months Ended</td><td colspan="2">Twelve Months Ended</td></tr>'
                '<tr><td></td>'+''.join('<td>'+d+'</td>' for d in ['December 31, 2024', 'December 31, 2023']*2)+'</tr>'
                '<tr><td>Net income</td><td>$ 1</td><td>2</td><td>$ 3</td><td>4</td></tr>'
                '<tr><td>Adjustments to reconcile net income:</td></tr>'
                '<tr><td>'+LABEL+'</td><td>999</td><td>888</td><td>314,159</td><td>27,182</td></tr>'
                '<tr><td>Net cash from operations</td><td>1</td><td>2</td><td>3</td><td>4</td></tr></table>')
        result, inv = parsed(text)
        self.assertEqual(result['value']['value_decimal'], '314159')
        self.assertEqual(inv['candidates'][0]['logical_columns'], [3])

    def test_non_gaap_duplicate_is_excluded(self):
        result, _ = parsed(table(title='NON-GAAP CONSOLIDATED STATEMENTS OF CASH FLOWS', amount='999')+table())
        self.assertEqual(result['value']['value_decimal'], '314159')

    def test_duplicate_formal_statements_hold(self):
        result, _ = parsed(table()+table())
        self.assertIsNone(result['value']); self.assertTrue(result['gaps'])

    def test_duplicate_sbc_rows_hold(self):
        result, _ = parsed(table(extra=row(amount='123')))
        self.assertIsNone(result['value'])
        self.assertIn('multiple_stock_compensation_rows', [x['reason'] for x in result['gaps']])

    def test_combined_tax_or_other_adjustment_rows_hold(self):
        for label in (LABEL+' and other expenses', LABEL+', net of tax', 'Capitalized '+LABEL):
            with self.subTest(label=label):
                result, _ = parsed(table(label=label))
                self.assertIsNone(result['value']); self.assertTrue(result['gaps'])
        result, _ = parsed(table(extra=row(label=LABEL+' and other')))
        self.assertIsNone(result['value'])

    def test_attributed_or_missing_indirect_start_hold(self):
        for ni in ('Net income attributable to common shareholders', 'Income from continuing operations', 'Profit'):
            result, _ = parsed(table(ni=ni))
            self.assertIsNone(result['value'])

    def test_no_value_outside_reconciliation(self):
        text = table().replace(row(), '').replace('</table>', row()+'</table>')
        result, _ = parsed(text)
        self.assertIsNone(result['value'])
        text = table().replace(row(), '').replace('<tr><td>Net income', row()+'<tr><td>Net income')
        self.assertIsNone(parsed(text)[0]['value'])

    def test_adjustment_heading_must_precede_sbc(self):
        text = table().replace(row(), '').replace('<tr><td>Adjustments', row()+'<tr><td>Adjustments')
        self.assertIsNone(parsed(text)[0]['value'])

    def test_invalid_or_footnoted_amount_not_guessed(self):
        for literal in ('NaN', 'Infinity', '-', '314 159', '31,41', '2%', '(3)-', '3<sup>1</sup>'):
            with self.subTest(literal=literal):
                result, _ = parsed(table(amount=literal))
                self.assertIsNone(result['value']); self.assertTrue(result['gaps'])

    def test_cross_period_cell_hold(self):
        text = table().replace(row(), '<tr><td>'+LABEL+'</td><td colspan="2">314,159</td></tr>')
        self.assertIsNone(parsed(text)[0]['value'])

    def test_mixed_scale_or_conflicting_currency_hold(self):
        for text in (table(units='millions and thousands'), table().replace('333', 'EUR 333')):
            self.assertIsNone(parsed(text)[0]['value'])

    def test_segmented_cashflow_uses_own_headers(self):
        bs = ('<table><tr><td colspan="3">CONSOLIDATED BALANCE SHEETS</td></tr>'
              '<tr><td colspan="3">(in millions)</td></tr><tr><td></td>'
              '<td>December 31, 2024</td><td>December 31, 2023</td></tr>'
              '<tr><td>Assets</td></tr><tr><td>Total assets</td><td>$ 8</td><td>7</td></tr>')
        cf = table().replace('<table><caption>CONSOLIDATED STATEMENTS OF CASH FLOWS (in millions)</caption>',
             '<tr><td colspan="3">CONSOLIDATED STATEMENTS OF CASH FLOWS</td></tr><tr><td colspan="3">(in millions)</td></tr>')
        result, inv = parsed(bs+cf)
        self.assertEqual(result['value']['value_decimal'], '314159')
        self.assertIn('statement_segment', inv['candidates'][0])


class PDFTests(unittest.TestCase):
    def test_compact_and_prefix_labels_metadata_only(self):
        for label in ('Stock-based compensation expense', 'Stock-based compensation',
                      'Share based compensation expense', 'Share\u2011based compensation'):
            with self.subTest(label=label):
                inv = pdf_parsed([pdf_text(label=label)])
                self.assertEqual(len(inv['candidates']), 1)
                text = m.base.safe.encoded(inv).decode()
                self.assertNotIn('314,159', text); self.assertNotIn('27,182', text)

    def test_letterspaced_label_and_title(self):
        text = pdf_text(label=' '.join(LABEL)).replace('Twelve Months Ended', 'T w e l v e M o n t h s E n d e d')
        self.assertEqual(len(pdf_parsed([text])['candidates']), 1)

    def test_signed_current_geometry_and_no_prior_literal(self):
        _, engine = geometry(values=('(314,159)', '27,182'))
        result, inv = pdf_parsed([pdf_text(amount='(314,159)')], engine)
        self.assertEqual(result['value']['value_decimal'], '-314159')
        self.assertTrue(result['value']['pdfium_text_agrees'])
        self.assertTrue(result['value']['independent_visual_review_required'])
        self.assertNotIn('27,182', m.base.safe.encoded(result).decode())
        self.assertIn('selected_cell', result['value']['pdfium_geometry'])
        self.assertEqual(inv['candidates'][0]['financial_column_index_0based'], 0)

    def test_duplicate_formal_page_or_sbc_hold(self):
        for texts in ([pdf_text(), pdf_text()], [pdf_text(extra=LABEL+'   1    2')]):
            inv = pdf_parsed(texts)
            self.assertTrue(inv['gaps'])

    def test_combined_or_net_tax_label_hold(self):
        for label in (LABEL+' and other', LABEL+' net of tax', 'Capitalized '+LABEL):
            self.assertTrue(pdf_parsed([pdf_text(label=label)])['gaps'])

    def test_quarter_and_non_gaap_not_used(self):
        quarter = pdf_text(duration='Three Months Ended')
        nongaap = pdf_text().replace('CONDENSED CONSOLIDATED', 'NON-GAAP CONSOLIDATED')
        inv = pdf_parsed([quarter, nongaap, pdf_text()])
        self.assertEqual(len(inv['candidates']), 1)
        self.assertEqual(inv['candidates'][0]['page_1based'], 3)

    def test_wrong_date_or_missing_duration_hold(self):
        for text in (pdf_text().replace('2024', '2022'), pdf_text(duration='Selected data')):
            self.assertFalse(pdf_parsed([text])['candidates'])

    def test_geometry_mismatch_or_column_crossing_hold(self):
        for values, x in [(('314,158', '27,182'), 480), (('314,159', '27,182'), 410)]:
            _, engine = geometry(values=values, second_x=x)
            result, _ = pdf_parsed([pdf_text()], engine)
            self.assertIsNone(result['value']); self.assertTrue(result['gaps'])

    def test_duplicate_physical_row_hold(self):
        p, engine = geometry()
        p.add(LABEL, 20, 370).add('314,159', 380, 370).add('27,182', 480, 370)
        result, _ = pdf_parsed([pdf_text()], engine)
        self.assertIsNone(result['value'])

    def test_missing_pdf_runtime_contract_rejected(self):
        with self.assertRaises(ValueError): m.inventory(b'%PDF-synthetic', PERIODS)


class ContractTests(unittest.TestCase):
    def test_changed_raw_or_inventory_rejected(self):
        data = table().encode(); inv = m.inventory(data, PERIODS)
        with self.assertRaises(ValueError): m.extract_current(data+b' ', PERIODS, inv)
        altered = deepcopy(inv); altered['candidates'][0]['scale'] = '1000'
        with self.assertRaises(ValueError): m.extract_current(data, PERIODS, altered)

    def test_changed_current_period_rejected(self):
        data = table().encode(); inv = m.inventory(data, PERIODS); changed = deepcopy(PERIODS)
        changed['current']['period_start'] = '2024-01-02'; changed['current']['days_inclusive'] = 365
        with self.assertRaises(ValueError): m.extract_current(data, changed, inv)

    def test_unknown_fields_bad_duration_and_empty_source_rejected(self):
        p = deepcopy(PERIODS); p['current']['extra'] = 'no'
        with self.assertRaises(ValueError): m.inventory(table().encode(), p)
        p = deepcopy(PERIODS); p['current']['days_inclusive'] = True
        with self.assertRaises(ValueError): m.inventory(table().encode(), p)
        for data in (b'', 'html', None):
            with self.assertRaises(ValueError): m.inventory(data, PERIODS)

    def test_missing_current_duration_is_explicit_gap(self):
        p = deepcopy(PERIODS); p['current'].update(period_start=None, days_inclusive=None)
        result, _ = parsed(table(), p)
        self.assertIsNone(result['value'])
        self.assertEqual(result['gaps'][0]['reason'], 'missing_current_annual_duration')

    def test_missing_prior_duration_never_promotes_old_hold(self):
        p = deepcopy(PERIODS); p['comparison'].update(period_start=None, days_inclusive=None)
        before = deepcopy(p); result, _ = parsed(table(), p)
        self.assertIsNotNone(result['value']); self.assertEqual(p, before)
        for key in ('fact_admitted', 'model_admitted', 'strategy_admitted',
                    'first_public_version_verified', 'complete_correction_history_verified',
                    'certified_daily_security_master'):
            self.assertIs(result[key], False)
        self.assertNotIn('cash_quality_admission', result)

    def test_accounting_review_flags_are_not_auto_cleared(self):
        result, _ = parsed(table()+'<p>Prior periods were retrospectively reclassified.</p>')
        flags = {flag['code'] for flag in result['accounting_review_flags']}
        self.assertIn('cashflow_accounting_change_context_unreviewed', flags)

    def test_hash_closure_lists_every_direct_local_helper(self):
        self.assertEqual(len(set(m.LOCAL_DEPENDENCIES)), len(m.LOCAL_DEPENDENCIES))
        for name in (m.SELF, m.TEST, m.base.SELF, m.html_repair.SELF, m.pdf_repair.SELF):
            self.assertIn(name, m.LOCAL_DEPENDENCIES)

    def test_report_binds_closure_and_preserves_test_log(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            result = unittest.TestResult()
            result.testsRun = 7
            with patch.object(m, 'code_hashes', return_value={'code.py': 'a'*64}):
                write_report(root, result, 'Synthetic test output')
            report = m.base.safe.read(root, OUT+'/PARSER_TESTS.json')
            self.assertEqual(report['source_code_hashes'], {'code.py': 'a'*64})
            self.assertEqual(report['tests_run'], 7)
            self.assertTrue(report['synthetic_only'])
            self.assertEqual(report['real_source_cells_extracted'], 0)
            self.assertEqual(report['test_output'], 'Synthetic test output')

    def test_report_forbidden_after_plan_exists(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root/OUT).mkdir(parents=True)
            (root/OUT/'PLAN.json').write_text('{}')
            with patch.object(m, 'code_hashes') as hashed:
                with self.assertRaises(ValueError):
                    write_report(root, unittest.TestResult())
                hashed.assert_not_called()
            self.assertFalse((root/OUT/'PARSER_TESTS.json').exists())

    def test_report_does_not_overwrite_failure_history(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root/OUT).mkdir(parents=True)
            original = b'{"passed":false,"tests_run":1}\n'
            (root/OUT/'PARSER_TESTS.json').write_bytes(original)
            with patch.object(m, 'code_hashes', return_value={'code.py': 'b'*64}):
                with self.assertRaises(FileExistsError):
                    write_report(root, unittest.TestResult())
            self.assertEqual((root/OUT/'PARSER_TESTS.json').read_bytes(), original)


def write_report(root, result, test_output=''):
    require = m.require
    require(not (root/OUT/'PLAN.json').exists(), 'Cannot publish parser tests after source PLAN exists')
    report = dict(schema_version=1, passed=result.wasSuccessful(), synthetic_only=True,
                  real_source_cells_extracted=0, failures=len(result.failures), errors=len(result.errors),
                  tests_run=result.testsRun, source_code_hashes=m.code_hashes(root),
                  test_output=test_output)
    # Exclusive publication preserves any earlier failure record instead of
    # overwriting evidence. Intermediate synthetic runs normally use /tmp logs.
    m.base.safe.publish(root, OUT+'/PARSER_TESTS.json', report)


if __name__ == '__main__':
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--write-report', action='store_true')
    args = cli.parse_args()
    suite = unittest.defaultTestLoader.loadTestsFromModule(sys.modules[__name__])
    stream = io.StringIO()
    result = unittest.TextTestRunner(stream=stream, verbosity=2).run(suite)
    sys.stderr.write(stream.getvalue())
    if args.write_report: write_report(Path(__file__).resolve().parents[1], result, stream.getvalue())
    sys.exit(0 if result.wasSuccessful() else 1)
