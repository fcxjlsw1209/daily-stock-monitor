 manifest=io.read(root,BASE+'/MANIFEST.json');audit=io.read(root,BASE+'/AUDIT.json')
 require(manifest['plan_sha256']==plan_sha and manifest['output_hashes']['RAW_FACTS.json']==data_sha,'manifest_binding')
 require(io.hash_file(root,BASE+'/AUDIT.json')==manifest['output_hashes']['AUDIT.json']and audit['data_sha256']==data_sha and audit['plan_sha256']==plan_sha,'audit_binding')
 io.verify_hashes(root,plan['source_hashes']);io.verify_hashes(root,plan['source_code_hashes'])
 specs={e['event_id']:e for e in plan['events']}
 selected=[e for e in data['events']if e['symbol']in ('AMD','MSFT','NVDA')]
 require(Counter(e['symbol']for e in selected)==Counter(AMD=10,MSFT=12,NVDA=12),'34_event_scope')
 require(len({e['event_id']for e in selected})==34,'duplicate_event')
 axis=io.read(root,SESSIONS)['sessions'];require(axis==sorted(set(axis)),'session_axis')
 rows=[];violations=[]
 for event in selected:
  spec=specs[event['event_id']];errors=[]
  for key,value in spec.items():
   if key!='locator_inventory'and event.get(key)!=value:errors.append('event_metadata_'+key)
  publication=event['release_date'];ix=bisect.bisect_right(axis,publication)
  if ix==len(axis)or axis[ix]!=event['available_from']:errors.append('not_next_session')
  if any(event.get(k)is not False for k in ('fact_admitted','model_admitted','strategy_admitted','first_public_version_verified','complete_correction_history_verified','certified_daily_security_master')):errors.append('unexpected_admission_or_certification')
  raw=io.local(root,event['source']['path']).read_bytes()
  require(io.digest(raw)==event['source']['sha256'],'raw_source_sha')
  candidates,rejections,notes=fresh_candidates(raw,event['periods'])
  cells=[]
  for side in SIDES:
   for field in FIELDS:
    cell=event['fields'][side][field];review=compare_cell(cell,candidates[side][field]);review.update(side=side,field=field)
    if cell is not None:
     for key,expected in (('source',event['source']),('period',event['periods'][side]),('available_from',event['available_from'])):
      if cell.get(key)!=expected:review['status']='mismatch';review['matched']=False;review['failures'].append(key+'_mismatch')
    cells.append(review)
  row=dict(event_id=event['event_id'],symbol=event['symbol'],fiscal_year=event['fiscal_year'],source=event['source'],metadata_errors=errors,
   cells=cells,producer_gaps=event['gaps'],inherited_rejection_codes=event['inherited_rejection_codes'],producer_accounting_flags=event['accounting_review_flags'],
   independent_accounting_notes=notes,accounting_scope_resolved=False,table_rejections=rejections,
   fact_admitted=False,model_admitted=False,strategy_admitted=False)
  if event['gaps']:
   row['gap_source_context']=gap_diagnostics(raw)
   classifications=[]
   for gap in event['gaps']:
    symbol=event['symbol'];year=event['fiscal_year'];field=gap['field']
    if symbol=='AMD'and year in (2015,2016,2017):
     reason='prior_annual_column_absent_from_current_formal_cashflow_statement'
    elif symbol=='AMD'and year in (2018,2020,2021,2022):
     reason='selected_cashflow_summary_only_no_formal_indirect_NI_start'
    elif symbol=='MSFT'and year==2018:
     reason='parser_format_limitation_spaced_thousands_separator'
    elif symbol=='MSFT'and year==2021:
     reason='parser_structure_limitation_multiple_statements_in_one_HTML_table'
    else:reason='formal_cashflow_table_not_found_in_this_cached_HTML'
    classifications.append(dict(side=gap['side'],field=field,classification=reason))
   row['gap_classifications']=classifications
   if event['symbol']=='MSFT'and event['fiscal_year']==2018:
    loc=spec['locator_inventory']['candidates']['current']['net_income'][0]
    table=BeautifulSoup(raw,'html.parser').find_all('table')[loc['table_index_zero_based']]
    _,physical,_=grid(table)
    items=[physical[(loc['row_index_zero_based'],pi)]for pi in loc['physical_cell_indices_zero_based']]
    row['unparsed_target_literal_evidence']=dict(locator=loc,physical_texts=[x['text']for x in items],physical_markup_sha256=[io.digest(x['markup'].encode())for x in items])
