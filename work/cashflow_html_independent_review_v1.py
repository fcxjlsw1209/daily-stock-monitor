def norm(text):return ' '.join(text.split()).rstrip(':').strip()
def require(ok,message):
 if not ok:raise ValueError(message)

def exact_money(text):
 text=norm(text).replace('\u2212','-')
 match=re.fullmatch(r'\$?\s*(\()?\s*(-?(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?)\s*(\))?',text)
 require(match is not None,'noncanonical_money')
 require(bool(match[1])==bool(match[3]),'unbalanced_parentheses')
 require(not(match[1]and match[2].startswith('-')),'double_negative')
 number=Decimal(match[2].replace(',',''))
 return format(number.copy_negate()if match[1]else number,'f')

def dates(text):
 hits=re.findall(r'\b('+'|'.join(sorted(MONTHS,key=len,reverse=True))+r')\.?\s+(\d{1,2}),?\s+(\d{4})\b',text,re.I)
 return sorted({date(int(y),MONTHS[m.lower()],int(d)).isoformat()for m,d,y in hits})

def is_label(field,label):
 label=norm(label).lower()
 if field=='total_assets':return label=='total assets'
 if field=='net_income':return label in ('net income','net loss','net income (loss)','net loss (income)')
 # Enumerate presentation variants, not financial derivations.
 return bool(re.fullmatch(r'(?:net )?cash (?:provided by(?:\s*\(used (?:in|for)\))?|used (?:in|for)(?:\s*\(provided by\))?|generated by|generated from|from) (?:operating activities|operations)',label))

def grid(table):
 rows=[row for row in table.find_all('tr')if row.find_parent('table')is table]
 cells={};expanded={}
 for ri,row in enumerate(rows):
  col=0
  for pi,el in enumerate(row.find_all(['td','th'],recursive=False)):
   while (ri,col)in expanded:col+=1
   rs=int(el.get('rowspan',1));cs=int(el.get('colspan',1))
   require(0<rs<=100 and 0<cs<=100,'invalid_span')
   cell=dict(row=ri,index=pi,text=norm(el.get_text(' ',strip=True)),start=col,width=cs,height=rs,markup=str(el))
   cells[(ri,pi)]=cell
   for dr in range(rs):
    for dc in range(cs):
     require((ri+dr,col+dc)not in expanded,'overlapping_cells');expanded[(ri+dr,col+dc)]=cell
   col+=cs
 return rows,cells,expanded

def header_parts(expanded,stop,column):
 seen=set();out=[]
 for ri in range(stop):
  cell=expanded.get((ri,column))
  if cell and (cell['row'],cell['index'])not in seen:
   seen.add((cell['row'],cell['index']))
   if cell['text']:out.append(cell['text'])
 return out

def context(table,physical,stop):
 inside=[c['text']for (ri,_),c in physical.items()if ri<stop and c['text']]
 if table.caption:inside.insert(0,norm(table.caption.get_text(' ',strip=True)))
 # Independent bounded predecessor traversal; never crosses a preceding table.
 outside=[];seen=set()
 for n,node in enumerate(table.previous_elements):
  if n>=300:break
  if not isinstance(node,Tag):continue
  if node.name=='table' or node.find_parent('table')is not None:break
  if node.name not in ('h1','h2','h3','h4','p','div','b','strong','font')or node.find('table'):continue
  text=norm(node.get_text(' ',strip=True))
  if not text or len(text)>500 or text in seen:continue
  outside.append(text);seen.add(text)
  if len(outside)>=16:break
 return inside+list(reversed(outside))

def inspect_table(table):
 rows,cells,expanded=grid(table)
 labels={ri:[c['text']for (r,_),c in cells.items()if r==ri and re.search('[A-Za-z]',c['text'])]for ri in range(len(rows))}
 starts=[ri for ri,ls in labels.items()if any(is_label('net_income',x)or re.fullmatch(r'assets|cash(?: and cash equivalents)?|total assets',x,re.I)for x in ls)]
 require(starts,'unknown_header_boundary')
 stop=min(starts);parts=context(table,cells,stop);text=' '.join(parts)
 require(not BAD.search(text),'adjusted_or_non_gaap_context')
 cf=bool(CF.search(text));bs=bool(BS.search(text));require(cf!=bs,'missing_or_ambiguous_statement_title')
 scales={x.lower()for x in re.findall(r'\b(millions|thousands)\b',text,re.I)}
 require(len(scales)==1,'ambiguous_or_missing_scale')
 scale={'millions':'1000000','thousands':'1000'}[scales.pop()]
 body=table.get_text(' ',strip=True)
 require('$'in body,'no_literal_currency')
 require(not re.search(r'[€£¥]|\b(?:EUR|GBP|JPY|CAD|AUD|HKD)\b',body,re.I),'conflicting_currency')
 ni=[ri for ri,ls in labels.items()if any(is_label('net_income',x)for x in ls)]
 ni_ok=(len(ni)==1 and not any(re.match(r'^net\s+(?:income|loss)\b',x,re.I)for ri,ls in labels.items()if ri<ni[0]for x in ls)
  and any(re.search(r'adjustments?\s+to\s+reconcile\s+(?:net\s+)?(?:income|loss)',x,re.I)for ri,ls in labels.items()if ri>ni[0]for x in ls))
 return dict(rows=rows,cells=cells,grid=expanded,labels=labels,stop=stop,scale=scale,cf=cf,bs=bs,ni_ok=ni_ok,
  title=(CF if cf else BS).search(text).group(0),context=parts)

def candidate_at(table,ti,field,end):
 state=inspect_table(table)
 require((field=='total_assets')==state['bs'],'different_statement')
 if field=='net_income':require(state['ni_ok'],'not_indirect_consolidated_start')
 cols=[]
 for col in sorted({c for _,c in state['grid']}):
  parts=header_parts(state['grid'],state['stop'],col);joined=' '.join(parts)
  if dates(joined)!=[end]:continue
  if field!='total_assets':
   require_annual=bool(re.search(r'\b(?:years?|(?:twelve|12)\s+months?)\s+ended\b',joined,re.I))
   quarter=bool(re.search(r'\b(?:three|six|nine|3|6|9)\s+months?\s+ended\b',joined,re.I))
   if not require_annual or quarter:continue
  cols.append(col)
 require(cols and cols==list(range(min(cols),max(cols)+1)),'missing_or_noncontiguous_annual_date_columns')
 out=[]
 for ri,labels in state['labels'].items():
  for label in labels:
   if not is_label(field,label):continue
   selected=[cell for (r,_),cell in state['cells'].items()if r==ri and set(range(cell['start'],cell['start']+cell['width'])).intersection(cols)]
   require(selected,'no_physical_cells')
   require(all(c['height']==1 and set(range(c['start'],c['start']+c['width'])).issubset(cols)for c in selected),'cross_period_or_row_span')
   display=' '.join(c['text']for c in selected if c['text'])
   value=exact_money(display)
   out.append(dict(table_index=ti,row_index=ri,physical_cell_indices=[c['index']for c in selected],logical_columns=cols,
    row_label=label,title=state['title'],scale=state['scale'],currency_literal='$',displayed_amount=display,value_decimal=value,
    parsed_cell_sha256=[io.digest(c['markup'].encode())for c in selected],
    headers=list(dict.fromkeys(x for col in cols for x in header_parts(state['grid'],state['stop'],col)))))
 return out

def fresh_candidates(raw,periods):
 soup=BeautifulSoup(raw,'html.parser')
 for tag in soup(['script','style']):tag.decompose()
 all_candidates={side:{f:[]for f in FIELDS}for side in SIDES};rejections=[]
 for ti,table in enumerate(soup.find_all('table')):
  for side in SIDES:
   for field in FIELDS:
    try:all_candidates[side][field]+=candidate_at(table,ti,field,periods[side]['period_end'])
    except (ValueError,KeyError,IndexError)as exc:
     rejections.append(dict(table_index=ti,side=side,field=field,reason=str(exc)))
 notes=[]
 for tag in soup.find_all(['p','li']):
  text=norm(tag.get_text(' ',strip=True))
  if re.search(r'\b(?:recast\w*|restat\w*|reclassif\w*|retrospect\w*|adopt\w*|accounting standards?)\b',text,re.I):
   notes.append(dict(text=text,text_sha256=io.digest(text.encode()),table_ancestor=tag.find_parent('table')is not None))
 return all_candidates,rejections,notes

def compare_cell(cell,candidates):
 if cell is None:
  return dict(status='producer_gap',independent_candidate_count=len(candidates),
   independently_located_candidates=candidates,matched=False)
 failures=[]
 if len(candidates)!=1:failures.append('independent_candidate_count_'+str(len(candidates)))
 matching=[]
 for c in candidates:
  loc=cell['locator']
  if(c['table_index'],c['row_index'],c['physical_cell_indices'])==(loc['table_index_zero_based'],loc['row_index_zero_based'],loc['physical_cell_indices_zero_based']):matching.append(c)
 if len(matching)!=1:failures.append('physical_source_locator_mismatch')
 else:
  c=matching[0]
  for key in ('displayed_amount','value_decimal','scale','currency_literal','parsed_cell_sha256'):
   if cell.get(key)!=c[key]:failures.append(key+'_mismatch')
  if cell['locator']['header_literals']!=c['headers']:failures.append('header_literals_mismatch')
  for key,expected in (('row_label',c['row_label']),('statement_title',c['title']),('logical_columns',c['logical_columns']),('scale',c['scale'])):
   if cell['locator'].get(key)!=expected:failures.append('locator_'+key+'_mismatch')
  if cell.get('fact_admitted')is not False:failures.append('unexpected_admission')
 return dict(status='matched'if not failures else'mismatch',matched=not failures,failures=failures,independent_candidate_count=len(candidates),
  independent_source=matching[0]if len(matching)==1 else None)

def gap_diagnostics(raw):
 soup=BeautifulSoup(raw,'html.parser');out=[]
 for ti,table in enumerate(soup.find_all('table')):
  try:rows,cells,expanded=grid(table)
  except ValueError:continue
  intro=context(table,cells,min(5,len(rows)))
  matching_rows=any(is_label('operating_cash_flow',c['text'])for c in cells.values())and any(is_label('net_income',c['text'])for c in cells.values())
  if not(CF.search(' '.join(intro))or re.search(r'selected cash flow information',' '.join(intro),re.I)or matching_rows):continue
  if BAD.search(' '.join(intro)):continue
  entries=[]
  ni_rows=[c['row']for c in cells.values()if is_label('net_income',c['text'])]
  for (ri,pi),cell in cells.items():
   text=cell['text']
   near_ni=any(n-8<=ri<n for n in ni_rows)
   if not re.search('[A-Za-z]',text)and not(near_ni and re.fullmatch(r'20\d{2}',text)):continue
   if ri<8 or near_ni or re.search(r'net\s+(?:income|loss)|cash.*(?:operat|activities)|adjustment|reconcil',text,re.I):
    entries.append(dict(row=ri,cell=pi,text=text))
  out.append(dict(table_index=ti,context=[x for x in intro if re.search('[A-Za-z]',x)and len(x)<180],labels_and_headers=entries))
 return out

def evaluate(root,plan_sha,data_sha,write=True):
 for value in (plan_sha,data_sha):require(type(value)is str and re.fullmatch('[0-9a-f]{64}',value),'Explicit SHA required')
