"""Record the root reviewer's completed image inspection, never an extraction input."""
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path.cwd()
BASE = Path("outputs/monthly_cashflow_source_preflight_v1")
EXPECTED_PLAN = "4161a752cfac3039ea733b000cab647b8c77c48562ef6f497d109aefc7be1472"
VALUES = {
    2016: ([321686, 290345], [45687, 53394], [65824, 81266], ["2016-09-24", "2015-09-26"]),
    2017: ([375319, 321686], [48351, 45687], [63598, 65824], ["2017-09-30", "2016-09-24"]),
    2018: ([365725, 375319], [59531, 48351], [77434, 64225], ["2018-09-29", "2017-09-30"]),
    2019: ([338516, 365725], [55256, 59531], [69391, 77434], ["2019-09-28", "2018-09-29"]),
    2020: ([323888, 338516], [57411, 55256], [80674, 69391], ["2020-09-26", "2019-09-28"]),
    2021: ([351002, 323888], [94680, 57411], [104038, 80674], ["2021-09-25", "2020-09-26"]),
    2022: ([352755, 351002], [99803, 94680], [122151, 104038], ["2022-09-24", "2021-09-25"]),
    2023: ([352583, 352755], [96995, 99803], [110543, 122151], ["2023-09-30", "2022-09-24"]),
    2024: ([364980, 352583], [93736, 96995], [118254, 110543], ["2024-09-28", "2023-09-30"]),
    2025: ([359241, 364980], [112010, 93736], [111482, 118254], ["2025-09-27", "2024-09-28"]),
}


def digest(path):
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def main():
    assert digest(BASE / "PLAN.json") == EXPECTED_PLAN
    inventory = json.loads((ROOT / BASE / "VISUAL_PAGES.json").read_text())
    assert inventory["plan_sha256"] == EXPECTED_PLAN
    inspected = []
    for entry in inventory["pages"]:
        page, year = entry["page_1based"], entry["fiscal_year"]
        if page not in (2, 3) and not (page == 4 and year in (2024, 2025)):
            continue
        assert digest(entry["image"]) == entry["sha256"]
        assert digest(entry["source"]["path"]) == entry["source"]["sha256"]
        rec = entry["source"]["receipt"]
        assert digest(rec["path"]) == rec["sha256"]
        inspected.append(entry)
    assert len(inspected) == 22
    rows = []
    for year, (assets, ni, cfo, dates) in sorted(VALUES.items()):
        pages = [x for x in inspected if x["fiscal_year"] == year]
        rows.append({
            "fiscal_year": year,
            "event_id": pages[0]["event_id"],
            "source": pages[0]["source"],
            "inspected_images": [{"path": x["image"], "sha256": x["sha256"],
                                  "page_1based": x["page_1based"]} for x in pages],
            "column_order": ["current", "comparison"],
            "period_end_dates": dates,
            "display_currency": "USD",
            "monetary_scale": "millions",
            "cash_flow_header": "Twelve Months Ended",
            "balance_sheet_page_1based": 2,
            "cash_flow_page_1based": 3,
            "visually_observed_total_assets": assets,
            "visually_observed_cash_flow_starting_net_income": ni,
            "visually_observed_cash_generated_by_operating_activities": cfo,
            "status": "visible_raw_amounts_only_not_accounting_or_temporal_admission",
        })
    out = {
        "schema_version": 1,
        "recorded_at_utc": datetime.now(timezone.utc).isoformat(),
        "review_method": "Root assistant inspected the rendered pixels with view_image before writing this receipt.",
        "purpose": "Independent image-check reference only. Never feed manually observed values into a production extractor, impute a missing source cell, or treat them as source admission.",
        "plan_sha256": EXPECTED_PLAN,
        "visual_inventory": {"path": str(BASE / "VISUAL_PAGES.json"),
                             "sha256": digest(BASE / "VISUAL_PAGES.json")},
        "recorder_sha256": digest("work/record_cashflow_apple_visual_review_v1.py"),
        "pages_inspected": 22,
        "monetary_cells_inspected": 60,
        "events": rows,
        "observations": [
            "All ten balance sheets say monetary amounts are in millions; the thousands exception is explicitly for share counts.",
            "All ten cash flow pages show two annual columns under Twelve Months Ended.",
            "The formal net income starting row is distinct from the following adjustments-to-reconcile prose that repeats net income and cash generated by operating activities.",
            "The final cash generated by operating activities subtotal is above investing activities.",
            "FY2018 comparative FY2017 CFO is 64,225 whereas the original FY2017 report shows 63,598. Record the difference and require accounting review; do not infer its cause from numerical resemblance.",
            "FY2024 and FY2025 page 4 are non-GAAP reconciliations, not the formal cash flow statement. Keep GAAP FY2024 NI 93,736; do not substitute adjusted 103,982.",
            "Page 4 describes the FY2024 European Court State Aid decision and a net one-time income tax charge. It does not justify removing the charge from GAAP fields.",
        ],
        "coverage_limitations": [
            "Page 1 was not visually inspected in this receipt.",
            "The observations establish visible field identity and display values, not first-public-version provenance, release-time certainty, absence of amendments, or accounting comparability.",
        ],
        "source_admitted": False,
        "financial_ratios_computed": 0,
        "rankings_or_portfolios_computed": 0,
        "frozen_inputs_changed": False,
    }
    target = ROOT / BASE / "APPLE_VISUAL_REVIEW.json"
    with target.open("x") as handle:
        json.dump(out, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    print(json.dumps({"output": str(target.relative_to(ROOT)), "sha256": digest(target),
                      "pages": 22, "cells": 60, "source_admitted": False}))


if __name__ == "__main__":
    main()
