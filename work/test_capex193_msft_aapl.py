class PreservationTests(unittest.TestCase):
    def test_success_does_not_remove_inherited_hold(self):
        e = event(); e['cash_quality_admission'] = {'admitted': False, 'reasons': ['unknown_comparison_duration']}
        e['inherited_rejection_codes'] = ['old_identity_hold']
        x = m.record(e, {'extraction_verified': True})
        self.assertEqual(x['status'], 'held'); self.assertTrue(x['extraction_verified'])
        self.assertIn('inherited:unknown_comparison_duration', x['hold_reasons'])
        self.assertEqual(x['inherited_rejection_codes'], ['old_identity_hold'])
        self.assertFalse(x['fact_admitted'])
    def test_failure_retained_record(self):
        x = m.record(event(), error='missing row')
        self.assertEqual(x['status'], 'held'); self.assertIsNone(x['field'])
        self.assertFalse(x['extraction_verified'])
    def test_write_once(self):
        with tempfile.TemporaryDirectory() as td:
            p = Path(td) / 'out.json'; m.publish(p, {'x': 1})
            with self.assertRaises(FileExistsError): m.publish(p, {'x': 2})
    def test_wrong_scope_cannot_read_sources(self):
        with patch.object(m, 'verify', side_effect=AssertionError('should not read')):
            with self.assertRaisesRegex(ValueError, 'Exact CAPEX193'): m.gate('0' * 64)


