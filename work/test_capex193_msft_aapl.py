import capex193_msft_aapl as m

PERIODS = {'current': {'period_start': '2029-07-01', 'period_end': '2030-06-30', 'days_inclusive': 365},
           'comparison': {'period_start': '2028-07-01', 'period_end': '2029-06-30', 'days_inclusive': 365}}


def html(label=m.HTML_LABEL, amount='(4,321)', duplicate=False, duration='Twelve Months Ended June 30,'):
    cap = '<tr><td>' + label + '</td><td>' + amount + '</td><td>(3,210)</td></tr>'
    return ('<h2>CASH FLOWS STATEMENTS</h2><p>(In millions)</p><table>'
            '<tr><td></td><td colspan="2">' + duration + '</td></tr>'
            '<tr><td></td><td>2030</td><td>2029</td></tr>'
            '<tr><td>Net income</td><td>$ 20</td><td>$ 10</td></tr>'
            '<tr><td>Adjustments to reconcile net income to cash generated by operating activities:</td><td></td><td></td></tr>'
            '<tr><td>Depreciation</td><td>2</td><td>1</td></tr>'
            '<tr><td>Net cash from operations</td><td>30</td><td>20</td></tr>'
            '<tr><td>Investing</td><td></td><td></td></tr>' + cap + (cap if duplicate else '') +
            '<tr><td>Net cash used in investing</td><td>(5,000)</td><td>(4,000)</td></tr>'
            '<tr><td>Financing</td><td></td><td></td></tr></table>').encode()


def event(raw=None):
    raw = raw or html()
    loc = m.html2.inventory(raw, PERIODS)['candidates']['current']['operating_cash_flow'][0]
    return dict(event_id='MSFT:FY2030:2030-07-25', symbol='MSFT', fiscal_year=2030, release_date='2030-07-25',
                available_from='2030-07-26', periods=deepcopy(PERIODS),
                fields={'current': {'operating_cash_flow': {'locator': loc}}},
                source={'path': 'synthetic.html', 'sha256': m.sha(raw)},
                cash_quality_admission={'admitted': True, 'reasons': []}, inherited_rejection_codes=[],
                accounting_review_flags=[], identity={'issuer_id': 'synthetic'})


def pdf_text(label=m.PDF_LABEL, amount='(7,123)', duplicate=False, annual='Twelve Months Ended'):
    row = label + '    ' + amount + '    (6,001)'
    return '\n'.join(['Apple Inc.', 'CONDENSED CONSOLIDATED STATEMENTS OF CASH FLOWS', '(Unaudited)',
                      '(In millions)', annual, 'June 30,                   June 30,', '2030                      2029',
                      'Net income    $ 100      $ 90',
                      'Adjustments to reconcile net income to cash generated by operating activities:',
                      'Depreciation    4      5', 'Cash generated by operating activities    110    100',
                      'Investing activities:', row] + ([row] if duplicate else []) +
                     ['Cash used in investing activities    (8000)    (7000)', 'Financing activities:'])


def pdf_event(text):
    e = event()
    e['symbol'] = 'AAPL'
    e['fields']['current']['operating_cash_flow']['locator'] = m.pdf4.inventory([text], PERIODS)['candidates']['current']['operating_cash_flow'][0]
    return e


class CashLiteralTests(unittest.TestCase):
    def test_parentheses_preserved_and_scale(self):
        x = m.outflow('(4,321)', '1000000')
        self.assertEqual(x['signed_literal'], '(4,321)')
        self.assertEqual(x['signed_value_decimal'], '-4321')
        self.assertEqual(x['positive_outflow_decimal'], '4321')
        self.assertEqual(x['scaled_positive_outflow_decimal'], '4321000000')
    def test_minus_and_explicit_zero(self):
        self.assertEqual(m.outflow('-42', '1000')['positive_outflow_decimal'], '42')
        self.assertEqual(m.outflow('0', '1000')['positive_outflow_decimal'], '0')
    def test_invalid_no_zero_fill_or_abs_inflow(self):
        for s in ('-', '—', '', '10', '(10', '1 234', 'NaN', '0.01%'):
            with self.subTest(s=s), self.assertRaises(ValueError):
                m.outflow(s, '1000000')
    def test_unsupported_units(self):
        with self.assertRaises(ValueError): m.outflow('(2)', '1')


class HTMLTests(unittest.TestCase):
    def test_annual_current_exact(self):
        raw = html(); e = event(raw); old = deepcopy(e)
        x = m.html_field(raw, e)
        self.assertEqual(x['positive_outflow_decimal'], '4321')
        self.assertEqual(x['locator']['logical_columns'], [1])
        self.assertEqual(x['locator']['period_end'], '2030-06-30')
        self.assertFalse(x['fact_admitted']); self.assertEqual(e, old)
        self.assertEqual(x['row_text_sha256'], m.sha(x['row_text'].encode()))
    def test_combined_or_lease_labels_held(self):
        for label in ('Additions to property and equipment and intangibles', 'Property acquired under finance leases'):
            raw = html(label=label)
            with self.subTest(label=label), self.assertRaisesRegex(ValueError, 'Unique pure'):
                m.html_field(raw, event(raw))
    def test_duplicate_rejected(self):
        raw = html(duplicate=True)
        with self.assertRaisesRegex(ValueError, 'Unique pure'): m.html_field(raw, event(raw))
    def test_wrong_cfo_locator_rejected(self):
        raw = html(); e = event(raw)
        e['fields']['current']['operating_cash_flow']['locator']['period_end'] = '2029-06-30'
        with self.assertRaisesRegex(ValueError, 'locator differs'): m.html_field(raw, e)
    def test_not_investing_held(self):
        raw = html().replace(b'<td>Investing</td>', b'<td>Operating</td>')
        with self.assertRaisesRegex(ValueError, 'investing section'): m.html_field(raw, event(raw))
    def test_period_spanning_cell_held(self):
        raw = html().replace(b'<td>(4,321)</td><td>(3,210)</td>', b'<td colspan="2">(4,321)</td>')
        with self.assertRaisesRegex(ValueError, 'multiple financial periods'): m.html_field(raw, event(raw))


class PDFTests(unittest.TestCase):
    def test_pdf_current_not_comparative(self):
        text = pdf_text(); x = m.pdf_layout([text], pdf_event(text))
        self.assertEqual(x['positive_outflow_decimal'], '7123')
        self.assertEqual(x['all_row_cells'], ['(7,123)', '(6,001)'])
        self.assertEqual(x['locator']['financial_column_index_0based'], 0)
        self.assertEqual(x['locator']['header_dates'], ['2030-06-30', '2029-06-30'])
    def test_pdf_separate_closing_parenthesis_is_preserved(self):
        text = pdf_text(amount='(7,123 )'); x = m.pdf_layout([text], pdf_event(text))
        self.assertEqual(x['signed_literal'], '(7,123 )')
        self.assertEqual(x['positive_outflow_decimal'], '7123')
        self.assertEqual(x['all_row_cells'], ['(7,123)', '(6,001)'])
        self.assertEqual(x['all_row_signed_literals'], ['(7,123 )', '(6,001)'])
    def test_pdf_digit_gaps_and_unmapped_tail_rejected(self):
        for tail in ('(7 123) (6,001)', '(7,123) [x] (6,001)', '(7,123) (6,001) 2'):
            with self.subTest(tail=tail), self.assertRaises(ValueError):
                m.pdf_monetary_cells(tail, 2)
    def test_pdf_combined_label_rejected(self):
        text = pdf_text(label=m.PDF_LABEL + ' and intangible assets')
        with self.assertRaises(ValueError): m.pdf_layout([text], pdf_event(text))
    def test_pdf_duplicate_and_sign_rejected(self):
        for text in (pdf_text(duplicate=True), pdf_text(amount='7,123')):
            with self.assertRaises(ValueError): m.pdf_layout([text], pdf_event(text))
    def test_pdf_interim_rejected(self):
        text = pdf_text(annual='Three Months Ended')
        with self.assertRaises((ValueError, IndexError)):
            m.pdf_layout([text], pdf_event(text))
    def test_pdf_financing_boundary_rejected(self):
        text = pdf_text().replace('Investing activities:', 'Financing activities:')
        with self.assertRaisesRegex(ValueError, 'investing activities'): m.pdf_layout([text], pdf_event(text))


class FakeTextPage:
    def __init__(self): self.chars = []
    def add(self, text, x, y):
        for c in text:
            self.chars.append((c, (x, y, x + 4, y + 8))); x += 5
        return self
    def count_chars(self): return len(self.chars)
    def get_text_range(self, index, count): return ''.join(c[0] for c in self.chars[index:index + count])
    def get_charbox(self, index): return self.chars[index][1]


