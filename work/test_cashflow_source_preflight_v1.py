def table(kind='cf',quarter=False,ni='Net income',scale='millions',values=('314,159','(27,182)'),adjustment=True):
 title='CONSOLIDATED STATEMENTS OF CASH FLOWS'if kind=='cf'else'CONSOLIDATED BALANCE SHEETS'
 heads='<tr><td></td><td>December 31, 2024</td><td>December 31, 2023</td></tr>'
 period='Three Months Ended'if quarter else'Years Ended'
 if kind=='cf':
  body=f'<tr><td>{ni}</td><td>$ {values[0]}</td><td>$ {values[1]}</td></tr>'
  if adjustment:body+='<tr><td>Adjustments to reconcile net income to net cash from operations:</td><td></td><td></td></tr>'
  body+='<tr><td>Net cash provided by operating activities</td><td>123,456</td><td>0</td></tr>'
